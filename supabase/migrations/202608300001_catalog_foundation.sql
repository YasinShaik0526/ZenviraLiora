create policy "Admins can view their role" on public.catalog_admins
for select to authenticated using (user_id = auth.uid());

create policy "Public can view active categories" on public.categories
for select using (active or public.is_catalog_admin());
create policy "Admins manage categories" on public.categories
for all to authenticated using (public.is_catalog_admin()) with check (public.is_catalog_admin());

create policy "Public can view active collections" on public.collections
for select using (active or public.is_catalog_admin());
create policy "Admins manage collections" on public.collections
for all to authenticated using (public.is_catalog_admin()) with check (public.is_catalog_admin());

